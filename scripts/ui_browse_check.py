import os, sys
from playwright.sync_api import sync_playwright
URL, OUT = sys.argv[1], sys.argv[2]
os.makedirs(OUT, exist_ok=True)
errs, res = [], []
def check(name, ok): res.append((name, bool(ok))); print(("PASS " if ok else "FAIL ") + name)
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={"width": 1440, "height": 900})
    pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.on("console", lambda m: m.type == "error" and errs.append(m.text))
    pg.goto(URL); pg.wait_for_selector("#screen-choose.active, #screen-choose:not(.hidden)", timeout=15000); pg.wait_for_timeout(1000)
    check("create card hidden", pg.locator('.choose-card[onclick="App.goCreate()"]').count() == 0)
    check("browse note shown", pg.locator("#browse-note:not(.hidden)").count() == 1)
    check("example button shown", pg.locator("#landing-example:not(.hidden)").count() == 1)
    pg.screenshot(path=f"{OUT}/1_landing.png")
    pg.click('.choose-card[onclick="App.goExisting()"]'); pg.wait_for_selector(".pick-card", timeout=15000)
    check("330 profiles listed", "330 of 330" in pg.inner_text("#picker-count"))
    pg.locator(".pick-card").nth(9).click(); pg.click("#existing-generate")
    pg.wait_for_selector("#graph-slot svg, #graph-slot canvas", timeout=20000); pg.wait_for_timeout(2500)
    check("network drawn", pg.locator("#graph-slot svg circle, #graph-slot svg g").count() > 5)
    check("chat button disabled", pg.locator("#chat-btn").is_disabled())
    pg.screenshot(path=f"{OUT}/2_network.png")
    pg.click("#contrast-btn"); pg.wait_for_selector(".ccard", timeout=20000); pg.wait_for_timeout(1500)
    check("3 contrast cards", pg.locator(".ccard").count() == 3)
    check("compare disabled", pg.locator(".ccard button.primary").first.is_disabled())
    pg.screenshot(path=f"{OUT}/3_contrast.png")
    pg.locator(".ccard").first.get_by_text("See a recorded example").click()
    pg.wait_for_selector("#replay-bar:not(.hidden)", timeout=15000); pg.wait_for_timeout(1500)
    for _ in range(3):
        pg.get_by_text("Next ▶").click(); pg.wait_for_timeout(800)
    check("replay plays", pg.locator("#replay-bar").count() == 1)
    pg.screenshot(path=f"{OUT}/4_replay.png")
    b.close()
check("no JS errors", not errs)
for e in errs[:10]: print("  JS:", e[:200])
sys.exit(0 if all(ok for _, ok in res) else 1)
